/** Mission chat model (local in phase 1/2 demo; mirrors public.messages / mission_events on Supabase). */
export type ChatParty = 'owner' | 'sitter';
export type PickupReason = 'completed' | 'early_owner' | 'early_sitter';

export const PICKUP_REASON_LABELS: Record<PickupReason, string> = {
  completed: 'Fin de mission prévue',
  early_owner: 'Le propriétaire reprend son animal plus tôt',
  early_sitter: 'Le Pet Sitter interrompt la garde',
};

export type LocalReview = { criteria: Record<string, number>; rating: number; comment?: string; createdAt: string };

export type ChatFile = { name: string; mime: string; uri: string; size?: number; width?: number; height?: number };

export type ChatMessage = {
  id: string;
  from: ChatParty | 'system';
  kind: 'text' | 'file' | 'event' | 'firstNight';
  body?: string;
  file?: ChatFile;
  createdAt: string;
};

export type NightAnswer = 'calm' | 'woke' | 'restless';
export type MorningAnswer = 'relaxed' | 'playful' | 'stressed' | 'tired';

export type FirstNightUpdate = {
  status: 'pending' | 'answered';
  night?: NightAnswer;
  morning?: MorningAnswer;
  comment?: string;
  photo?: ChatFile;
  answeredAt?: string;
  rewardPoints: number;
};

export type MissionChat = {
  requestId: string;
  status: 'confirmed' | 'in_progress' | 'completed';
  dropoffCode: string;
  dropoffAttempts: number;
  startedAt?: string;
  /** Pick-up code generated by the sitter (shown to the sitter only; the owner types it). */
  pickupCode?: string;
  pickupReason?: PickupReason;
  endedAt?: string;
  /** Dev-only demo clock offset (hours) to show 48 h photo reminders without waiting. */
  demoOffsetHours?: number;
  reviews?: Partial<Record<ChatParty, LocalReview>>;
  confirmedAt: string;
  messages: ChatMessage[];
  firstNight: FirstNightUpdate;
};

export const NIGHT_LABELS: Record<NightAnswer, string> = {
  calm: 'Tranquillement',
  woke: 'Il s’est réveillé plusieurs fois',
  restless: 'Nuit agitée',
};

export const MORNING_LABELS: Record<MorningAnswer, string> = {
  relaxed: 'Calme et détendu',
  playful: 'Actif et joueur',
  stressed: 'Un peu stressé',
  tired: 'Plus fatigué que d’habitude',
};
