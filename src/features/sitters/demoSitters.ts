import { getCity } from './cities';

/**
 * Demo Pet Sitters for phase 1 (local data only). Removed in phase 2 when real sitters sign up.
 * Daily rates are expressed as a markup on the country minimum so they always respect the floor.
 */
const ALL_SIZES: SizeCategory[] = ['cat', 'dogSmall', 'dogMedium', 'dogLarge', 'dogXL'];

function rates(cityId: string, markup: number, sizes: SizeCategory[] = ALL_SIZES) {
  const grid = MIN_DAILY_PRICE[getCity(cityId).country];
  const out: Partial<Record<SizeCategory, number>> = {};
  for (const s of sizes) out[s] = Math.round((grid[s] * markup) / 10) * 10;
  return out;
}

function near(cityId: string, dLatKm: number, dLngKm: number) {
  const c = getCity(cityId);
  return { lat: c.lat + dLatKm * 0.009, lng: c.lng + dLngKm * 0.013 };
}

